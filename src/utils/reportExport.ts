import type { AnyGenerationResult, CreatorProfile } from '../types/seo';

export function formatResultAsMarkdown(
  title: string,
  profile: CreatorProfile,
  payload: AnyGenerationResult
): string {
  const lines: string[] = [
    `# ${title}`,
    `Generated by INSTarank AI — All Creator SEO Studio`,
    `Date: ${new Date().toLocaleString()}`,
    '',
    '## Creator Profile Context',
    `- Creator Mode: ${profile.creatorMode}`,
    `- Creator Type: ${profile.creatorType}`,
    `- Instagram Niche: ${profile.niche}`,
    `- Content Topic: ${profile.topic}`,
    `- Target Audience: ${profile.targetAudience}`,
    `- Target Country: ${profile.targetCountry}`,
    `- Content Language: ${profile.language}`,
    `- Account Type: ${profile.accountType}`,
    `- Content Goals: ${profile.contentGoals}`,
    `- Brand Voice: ${profile.brandVoice}`,
    '',
  ];

  switch (payload.module) {
    case 'universal': {
      const d = payload.data;
      lines.push('## Universal Instagram SEO Results');
      lines.push('### SEO-Friendly Titles');
      d.titles.forEach((t, i) => lines.push(`${i + 1}. ${t}`));
      lines.push('', '### Optimized Captions');
      d.captions.forEach((c) => {
        lines.push(`#### ${c.style}`, c.text, '');
      });
      lines.push('### Primary Keywords', d.primaryKeywords.join(', '), '');
      lines.push('### Secondary Keywords', d.secondaryKeywords.join(', '), '');
      lines.push('### Long-Tail Keywords', d.longTailKeywords.join(', '), '');
      lines.push('### Related Search Terms', d.relatedSearchTerms.join(', '), '');
      lines.push('### Hashtags (40)', d.hashtags.join(' '), '');
      lines.push('### SEO Alt Text', d.altText, '');
      lines.push('### First Comment', d.firstComment, '');
      lines.push('### CTA Suggestions', ...d.ctaSuggestions.map((c) => `- ${c}`), '');
      lines.push('### Cover Text Ideas', ...d.coverTextIdeas.map((c) => `- ${c}`), '');
      lines.push(
        '### Estimated SEO Score Breakdown',
        `- Overall: ${d.scoreBreakdown.overallScore}/100`,
        `- Caption: ${d.scoreBreakdown.captionScore}/100`,
        `- Keyword: ${d.scoreBreakdown.keywordScore}/100`,
        `- Hashtag Relevance: ${d.scoreBreakdown.hashtagRelevance}/100`,
        `- Readability: ${d.scoreBreakdown.readability}/100`,
        `- CTA: ${d.scoreBreakdown.ctaScore}/100`
      );
      break;
    }
    case 'reels': {
      const d = payload.data;
      lines.push('## Instagram Reels SEO');
      lines.push('### Reel Titles', ...d.reelTitles.map((t, i) => `${i + 1}. ${t}`), '');
      lines.push('### 10 Attention-Grabbing Hooks', ...d.hooks.map((h, i) => `${i + 1}. ${h}`), '');
      lines.push('### Reel Captions');
      d.captions.forEach((c) => lines.push(`#### ${c.angle}`, c.text, ''));
      lines.push('### Spoken Audio Keywords', d.spokenAudioKeywords.join(', '), '');
      lines.push('### On-Screen Text Overlays', ...d.onScreenText.map((o) => `- ${o}`), '');
      lines.push('### Cover Title', d.coverTitle, '');
      lines.push('### CTA', d.cta, '');
      lines.push('### Content Description & Pacing', d.contentDescription, '');
      lines.push('### Hashtags', d.hashtags.join(' '), '');
      break;
    }
    case 'post_carousel': {
      const d = payload.data;
      lines.push('## Instagram Post & Carousel SEO');
      lines.push('### Carousel Titles', ...d.carouselTitles.map((t, i) => `${i + 1}. ${t}`), '');
      lines.push('### Slide-by-Slide Content Plan');
      d.slides.forEach((s) => {
        lines.push(`**Slide ${s.slideNumber}: ${s.heading}**`, s.body, `Visual Direction: ${s.visualDirection}`, '');
      });
      lines.push('### SEO Captions');
      d.seoCaptions.forEach((c) => lines.push(`#### ${c.style}`, c.text, ''));
      lines.push('### Engagement Questions', ...d.engagementQuestions.map((q) => `- ${q}`), '');
      lines.push('### Alt Text', d.altText, '');
      lines.push('### Hashtags', d.hashtags.join(' '), '');
      break;
    }
    case 'profile': {
      const d = payload.data;
      lines.push('## Instagram Profile SEO');
      lines.push('### Username Ideas', ...d.usernameIdeas.map((u) => `- ${u}`), '');
      lines.push('### Searchable Display Name', d.displayName, '');
      lines.push('### SEO-Optimized Bio', d.seoBio, '');
      lines.push('### Profile Keywords', d.profileKeywords.join(', '), '');
      lines.push('### Niche Positioning', d.nichePositioning, '');
      lines.push('### Bio CTA', d.cta, '');
      lines.push('### Improvement Tips', ...d.improvementTips.map((t) => `- ${t}`), '');
      break;
    }
    case 'caption_optimizer': {
      const d = payload.data;
      lines.push('## Caption Optimizer Report');
      lines.push('### Improved Caption', d.improvedCaption, '');
      lines.push('### Improved Hashtags', d.improvedHashtags.join(' '), '');
      lines.push(
        '### Diagnostic Analysis',
        `- SEO Quality: ${d.analysis.seoQuality}`,
        `- Keyword Placement: ${d.analysis.keywordPlacement}`,
        `- Readability: ${d.analysis.readabilityFeedback}`,
        `- Engagement Potential: ${d.analysis.engagementPotential}`,
        `- CTA Quality: ${d.analysis.ctaQuality}`,
        `- Hashtag Relevance: ${d.analysis.hashtagRelevanceFeedback}`
      );
      break;
    }
    case 'hashtags': {
      const d = payload.data;
      lines.push('## Categorized Hashtag Studio');
      lines.push('### Broad', d.broad.join(' '), '');
      lines.push('### Medium', d.medium.join(' '), '');
      lines.push('### Niche', d.niche.join(' '), '');
      lines.push('### Long-Tail', d.longTail.join(' '), '');
      lines.push('### Strategy Note', d.strategyNote, '');
      break;
    }
    case 'content_ideas': {
      const d = payload.data;
      lines.push('## Creator Content Ideas & Strategy');
      lines.push('### 30 Content Ideas', ...d.contentIdeas.map((c, i) => `${i + 1}. ${c}`), '');
      lines.push('### 10 Reel Ideas', ...d.reelIdeas.map((r, i) => `${i + 1}. ${r}`), '');
      lines.push('### 10 Viral-Style Hooks', ...d.viralHooks.map((h, i) => `${i + 1}. ${h}`), '');
      lines.push('### 10 Carousel Ideas', ...d.carouselIdeas.map((c, i) => `${i + 1}. ${c}`), '');
      lines.push('### Weekly Content Strategy');
      d.weeklyStrategy.forEach((w) => {
        lines.push(`- **${w.day} (${w.format})**: ${w.topic} — Goal: ${w.goal} | Hook: ${w.hookIdea}`);
      });
      break;
    }
    case 'competitor': {
      const d = payload.data;
      lines.push('## Competitor Content Analysis');
      lines.push(`> ${d.disclaimer}`, '');
      lines.push('### Content Themes', ...d.contentThemes.map((t) => `- ${t}`), '');
      lines.push('### Caption Structure', d.captionStructure, '');
      lines.push('### Keyword Strategy', d.keywordStrategy.join(', '), '');
      lines.push('### Hashtag Patterns', d.hashtagPatterns, '');
      lines.push('### Content Opportunities', ...d.contentOpportunities.map((o) => `- ${o}`), '');
      lines.push('### Differentiation Actions', ...d.differentiationActions.map((a) => `- ${a}`), '');
      break;
    }
  }

  return lines.join('\n');
}

export function downloadTextFile(filename: string, content: string) {
  const blob = new Blob([content], { type: 'text/markdown;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
